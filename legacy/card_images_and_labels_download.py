import json
import os
import re
import time

import requests
from tqdm import tqdm

def get_assets_dir():
    # Get the directory where the script is located
    script_dir = os.path.dirname(os.path.abspath(__file__))
    # Go up one level to the project root and then into assets
    return os.path.join(script_dir, "..", "assets")


def _get(url, retries=4, backoff=1.5):
    """GET with exponential backoff. Raises on final failure."""
    delay = backoff
    for attempt in range(retries):
        try:
            response = requests.get(url, timeout=15)
            if response.status_code == 429:
                wait = int(response.headers.get("Retry-After", delay))
                print(f"  Rate limited — waiting {wait}s")
                time.sleep(wait)
                continue
            response.raise_for_status()
            time.sleep(0.1)  # be polite to TCGDex
            return response
        except requests.exceptions.RequestException as e:
            if attempt < retries - 1:
                print(f"  Retry {attempt + 1}/{retries - 1} for {url} ({e})")
                time.sleep(delay)
                delay *= 2
            else:
                raise
    raise RuntimeError(f"Failed after {retries} attempts: {url}")

#creates cards_metadata_{setName}.json with the cardlist for that set, if updateAll=true overwrite the
#json regardless of the file existing or not
def singleSetRequest(setId, setName, metadata_dir=None, updateAll=False):
    if metadata_dir is None:
        metadata_dir = os.path.join(get_assets_dir(), "metadata_dir")
    
    # Create the "metadata_dir" folder
    os.makedirs(metadata_dir, exist_ok=True)

    # Sanitize set name for filename
    setName_clean = setName.replace(" ", "")
    file_path = os.path.join(metadata_dir, f"cards_metadata_{setName_clean}.json")

    # Skip request if file exists and updateAll is False
    if not updateAll and os.path.exists(file_path):
        print(f"Metadata for {setName} already exists. Skipping download.")
        return

    # GET request to fetch the specified set
    API_URL_SINGLESET = f"https://api.tcgdex.net/v2/en/sets/{setId}"
    response = _get(API_URL_SINGLESET)

    if response.status_code == 200:
        cards = response.json()

        with open(file_path, "w") as file:
            json.dump(cards, file, indent=4)

        # Count and print the number of cards in the set
        number_of_card_in_set = len(cards.get("cards", []))
        print(f"Downloaded metadata for {number_of_card_in_set} cards in the {setName} Set.")
    else:
        print(f"Failed to fetch data: {response.status_code} {response.json()}")

def ImgDownload(setId, setName, metadata_dir, updateAll=False):
    # Open the metadata file generated by singleSetRequest()
    file_path = os.path.join(metadata_dir, f"cards_metadata_{setName}.json".replace(" ", ""))

    with open(file_path, "r") as file:
        cards = json.load(file)

    # Create the folder to store images
    image_dir_path = os.path.join(get_assets_dir(), "card_images")
    os.makedirs(image_dir_path, exist_ok=True)

    skipped_count = 0
    downloaded_count = 0

    # Iterate over each card in the set
    for card in tqdm(cards['cards'], desc=f"Downloading {setName} images", unit="card"):
        try:
            # Retrieve the image URL from the metadata and append quality and extension
            image_url = card["image"] + "/" + f"{IMAGE_QUALITY}.{IMG_EXTENSION}"

            if image_url:
                # Extract card ID and name
                card_id = card.get("id")
                card_name = card.get("name")

                # Keep your sanitization
                file_name = image_url.replace("/", "_")
                file_name = re.sub(r'^https:__assets.tcgdex.net_', '', file_name)

                # Construct full file path (card name + sanitized URL) and add extension
                file_path = os.path.join(image_dir_path, f"{card_name}-{file_name}")
                file_path = ''.join(file_path.split())  # remove spaces
                if not file_path.endswith(f".{IMG_EXTENSION}"):
                    file_path += f".{IMG_EXTENSION}"

                # Skip if the image already exists (unless updateAll=True)
                if os.path.exists(file_path) and not updateAll:
                    skipped_count += 1
                    continue

                try:
                    # GET request to fetch the card image
                    img_data = _get(image_url).content

                    # Save the image
                    with open(file_path, "wb") as img_file:
                        img_file.write(img_data)
                    downloaded_count += 1

                except Exception as e:
                    print(f"Failed to download {card_id}: {e}")
        except Exception:
            print("No image found, skipping")

    # Print summary
    print(f"\nDownload Summary for {setName}:")
    print(f"Total cards in set: {len(cards['cards'])}")
    print(f"Successfully downloaded: {downloaded_count}")
    print(f"Skipped (already existing): {skipped_count}")




def generateLabels(setId, setName, metadata_dir=None, updateAll=False):
    if metadata_dir is None:
        metadata_dir = os.path.join(get_assets_dir(), "metadata_dir")

    setName_clean = setName.replace(" ", "")

    # Open the metadata folder and read the set file
    set_file_path = os.path.join(metadata_dir, f"cards_metadata_{setName_clean}.json")
    with open(set_file_path, "r") as file:
        cards = json.load(file)

    # Create the "image_labels" folder
    annotations_dir = os.path.join(get_assets_dir(), "image_labels")
    os.makedirs(annotations_dir, exist_ok=True)

    skipped_count = 0
    downloaded_count = 0

    # Generate details for each card
    for card in tqdm(cards['cards'], desc=f"Generating {setName_clean} labels", unit="card"):
        cardId = card.get("id")
        if not cardId:
            print("⚠️ Card without ID found, skipping...")
            continue

        # Request card details
        API_URL_SINGLE_CARD = f"https://api.tcgdex.net/v2/en/cards/{cardId}"
        try:
            response = _get(API_URL_SINGLE_CARD)
        except Exception as e:
            print(f"⚠️ Failed to fetch card {cardId}: {e}")
            continue

        card_obtained = response.json()

        try:
            card_id = card_obtained["id"]
            card_name = card_obtained["name"].replace(" ", "")
            label_file_path = os.path.join(annotations_dir, f"labels_{card_id}_{card_name}.json")

            if os.path.exists(label_file_path) and not updateAll:
                skipped_count += 1
                continue

            with open(label_file_path, "w") as json_file:
                json.dump(card_obtained, json_file, indent=4)

            downloaded_count += 1

        except Exception as e:
            print(f"⚠️ Failed to create label for card {cardId}: {e}")
            continue

    # Print summary
    print(f"\n📑 Label Generation Summary for {setName_clean}:")
    print(f"Total cards in set: {len(cards['cards'])}")
    print(f"✅ Successfully generated labels: {downloaded_count}")
    print(f"⏩ Skipped (already existing): {skipped_count}")


